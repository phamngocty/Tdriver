// Map weather icon code to icon index
// Returns: 0=sunny, 1=cloudy, 2=rainy, 3=snowy, -1=unknown
int getWeatherIconIndex(const char *iconCode)
{
    if (!iconCode)
        return -1;
    // Standard OpenWeatherMap icon codes: 01d, 01n (clear)
    if (iconCode[0] == '0' && iconCode[1] == '1')
        return 0; // sunny
    if (iconCode[0] == '0' && iconCode[1] == '2')
        return 1; // cloudy (few clouds)
    if (iconCode[0] == '0' && iconCode[1] == '3')
        return 1; // cloudy (scattered)
    if (iconCode[0] == '0' && iconCode[1] == '4')
        return 1; // cloudy (broken)
    if (iconCode[0] == '0' && iconCode[1] == '9')
        return 2; // rainy (showers)
    if (iconCode[0] == '1' && iconCode[1] == '0')
        return 2; // rainy
    if (iconCode[0] == '1' && iconCode[1] == '1')
        return 2; // rainy (thunderstorm)
    if (iconCode[0] == '1' && iconCode[1] == '3')
        return 3; // snowy
    if (iconCode[0] == '5' && iconCode[1] == '0')
        return 3; // snowy
    return -1;
}
